    static String translate(String text, boolean german) {
        return !german || text == null ? text : DE.getOrDefault(text, text);
    }
    static String t(Object value) { return translate(String.valueOf(value), WuKongLanguage.german()); }
    static String slot(String value) {
        if (!WuKongLanguage.german()) return value;
        if (value.matches("Main [0-9]{2}(, [0-9]+)*")) return "Inventar " + value.substring(5);
        if (value.matches("Menu slot [0-9]+")) return "Menüslot " + value.substring(10);
        return t(value);
    }
    static String nested(String value) {
        if (!WuKongLanguage.german()) return value;
        if (value.startsWith("Container component: ")) return value.replace("Container component: ", "Behälterkomponente: ").replace(" occupied entries", " belegte Einträge").replace(" (partial)", " (teilweise)");
        if (value.startsWith("Bundle component: ")) return value.replace("Bundle component: ", "Bündelkomponente: ").replace(" entries", " Einträge").replace(" (partial)", " (teilweise)");
        return value;
    }
    static String message(String value) {
        if (!WuKongLanguage.german()) return value;
        String direct = t(value);
        if (!direct.equals(value)) return direct;
        for (String prefix : new String[]{"Latest published: ","Update available: ","Installed release matches ","Installed version is newer than ","Release check failed: "}) {
            if (value.startsWith(prefix)) return t(prefix) + value.substring(prefix.length());
        }
        return value;
    }
